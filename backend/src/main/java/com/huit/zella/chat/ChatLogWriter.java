package com.huit.zella.chat;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import java.sql.Timestamp;
import java.time.Instant;

@Component
public class ChatLogWriter {
    private static final Logger log = LoggerFactory.getLogger(ChatLogWriter.class);
    private final JdbcTemplate jdbc;
    private final ObjectMapper json = new ObjectMapper();

    public ChatLogWriter(JdbcTemplate jdbc) { this.jdbc = jdbc; }

    public void save(Long userId, String message, ChatResponse response, String intent) {
        try {
            jdbc.update("""
                    INSERT INTO chat_logs (user_id, user_message, bot_response, detected_intent, is_fallback, created_at)
                    VALUES (?, ?, ?, ?, ?, ?)
                    """, userId, message, json.writeValueAsString(response), intent, response.fallback(), Timestamp.from(Instant.now()));
        } catch (Exception exception) {
            // A history outage must not discard a response already generated by Rasa.
            log.warn("Could not save chat history ({})", exception.getClass().getSimpleName());
        }
    }
}
